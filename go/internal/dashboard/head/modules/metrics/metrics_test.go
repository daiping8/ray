func TestEnvConfig(t *testing.T) {
	os.Setenv("RAY_GRAFANA_HOST", "http://grafana:3000")
	os.Setenv("RAY_PROMETHEUS_HOST", "http://prom:9090")
	os.Setenv("RAY_GRAFANA_ORG_ID", "42")
	defer os.Unsetenv("RAY_GRAFANA_HOST")
	defer os.Unsetenv("RAY_PROMETHEUS_HOST")
	defer os.Unsetenv("RAY_GRAFANA_ORG_ID")

	m := newTestMetrics()
	if m.grafanaHost != "http://grafana:3000" || m.prometheusHost != "http://prom:9090" || m.grafanaOrgID != "42" {
		t.Fatalf("env config not applied: %+v", m)
	}
}

func contains(s, sub string) bool {
	return len(s) >= len(sub) && indexOf(s, sub) >= 0
}

func indexOf(s, sub string) int {
	for i := 0; i+len(sub) <= len(s); i++ {
		if s[i:i+len(sub)] == sub {
			return i
		}
	}
	return -1
}
