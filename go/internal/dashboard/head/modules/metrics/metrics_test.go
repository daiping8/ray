func TestPrometheusHealthSendsHeaders(t *testing.T) {
	var gotHeader string
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		gotHeader = r.Header.Get("X-Prom-Auth")
		w.WriteHeader(http.StatusOK)
	}))
	defer srv.Close()

	m := New(&head.HeadConfig{}, nil)
	m.prometheusHost = srv.URL
	m.prometheusHeaders = map[string]string{"X-Prom-Auth": "secret"}
	rr := serveHealth(t, m, "/api/prometheus_health")
	if rr.Code != http.StatusOK {
		t.Fatalf("status = %d, want 200", rr.Code)
	}
	if gotHeader != "secret" {
		t.Fatalf("prometheus header = %q, want secret", gotHeader)
	}
}

